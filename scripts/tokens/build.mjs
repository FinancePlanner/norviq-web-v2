// Generates the web's colour files from design/tokens.json (DS 2.0 § 5.1):
//   src/lib/styles/legacy/theme.tokens.css  every colour token with a css name, as OKLCH;
//   src/lib/charts/palette.generated.ts     chart fallbacks, as hex;
//   src/lib/theme-color.generated.ts        the page background, as hex (theme.svelte.ts);
//   src/app.html                            the two theme-color metas.
//
//   bun scripts/tokens/build.mjs            write them
//   bun scripts/tokens/build.mjs --check    exit 1 if any is stale (CI)
//   --tokens <path>                         read another tokens file (tests)
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { oklchCss } from './oklch.mjs';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const NOTICE = 'GENERATED by scripts/tokens/build.mjs from design/tokens.json; do not edit';
const CSS_OUT = 'src/lib/styles/legacy/theme.tokens.css';
const TS_OUT = 'src/lib/charts/palette.generated.ts';
// Its own module: theme.svelte.ts is in every route's entry, the chart palette is not.
const PAGE_OUT = 'src/lib/theme-color.generated.ts';
const HTML = 'src/app.html';

// charts/theme.ts ChartPalette key -> token path.
const CHART = {
	axis: 'color.chart.axis',
	grid: 'color.chart.grid',
	line: 'color.chart.line',
	lineAlt: 'color.chart.lineAlt',
	up: 'color.data.gain',
	down: 'color.data.loss',
	tooltipBg: 'color.chart.tooltipBg',
	tooltipBorder: 'color.chart.tooltipBorder',
	tooltipText: 'color.chart.tooltipText',
	pointer: 'color.chart.pointer',
	emphasisBorder: 'color.surface.card'
};

/**
 * @typedef {{ path: string; light: string; dark: string; css?: string }} ColorToken
 * @param {Record<string, any>} node
 * @param {string} [prefix]
 * @returns {ColorToken[]}
 */
function colorTokens(node, prefix = '') {
	return Object.entries(node).flatMap(([key, value]) => {
		if (key.startsWith('$') || !value || typeof value !== 'object') return [];
		const path = prefix ? `${prefix}.${key}` : key;
		if (!('$value' in value)) return colorTokens(value, path);
		if (value.$type !== 'color') return [];
		const { dark, css } = value.$extensions?.norviq ?? {};
		if (!dark) throw new Error(`${path}: no $extensions.norviq.dark`);
		return [{ path, light: value.$value, dark, css }];
	});
}

/** @param {ColorToken[]} colors */
function renderCss(colors) {
	const named = colors.filter((t) => t.css);
	/** @param {ColorToken} t @param {string} hex */
	const line = (t, hex) => `\t${t.css}: ${oklchCss(hex)}; /* ${hex} ${t.path} */`;
	return [
		`/* ${NOTICE}. */`,
		'/* html.dark carries only the tokens whose dark value differs. */',
		'',
		':root {',
		...named.map((t) => line(t, t.light)),
		'}',
		'',
		'html.dark {',
		...named.filter((t) => t.dark !== t.light).map((t) => line(t, t.dark)),
		'}',
		''
	].join('\n');
}

/** @param {Map<string, ColorToken>} byPath */
function renderTs(byPath) {
	/** @param {string} path */
	const token = (path) => {
		const t = byPath.get(path);
		if (!t) throw new Error(`missing token ${path}`);
		return t;
	};
	/** @param {'light' | 'dark'} scope */
	const record = (scope) =>
		Object.entries(CHART)
			.map(([key, path]) => `\t${key}: '${token(path)[scope].toLowerCase()}'`)
			.join(',\n');
	/** @param {'light' | 'dark'} scope */
	const pillars = (scope) =>
		['fundamentals', 'futureYou', 'fun']
			.map((key) => `\t\t${key}: '${token(`color.pillar.${key}`)[scope]}'`)
			.join(',\n');
	return [
		`// ${NOTICE}.`,
		'// Chart colours for when a --chart-* property is missing (charts/theme.ts).',
		'',
		`export const LIGHT = {\n${record('light')}\n} as const;`,
		'',
		`export const DARK = {\n${record('dark')}\n} as const;`,
		'',
		"export type PillarKey = 'fundamentals' | 'futureYou' | 'fun';",
		`export const PILLAR: { light: Record<PillarKey, string>; dark: Record<PillarKey, string> } = {\n\tlight: {\n${pillars('light')}\n\t},\n\tdark: {\n${pillars('dark')}\n\t}\n};`,
		'',
		`export const ACCENT_ACTION: { light: string; dark: string } = {\n\tlight: '${token('color.accent.action').light}',\n\tdark: '${token('color.accent.action').dark}'\n};`,
		'',
		'// color.data.flat: the neutral series colour (pillarColor, no --muted-foreground here).',
		`export const FLAT = {\n\tlight: '${token('color.data.flat').light.toLowerCase()}',\n\tdark: '${token('color.data.flat').dark.toLowerCase()}'\n} as const;`,
		''
	].join('\n');
}

/** @param {Map<string, ColorToken>} byPath */
function renderPageTs(byPath) {
	const page = byPath.get('color.surface.page');
	if (!page) throw new Error('missing token color.surface.page');
	return [
		`// ${NOTICE}.`,
		'// color.surface.page: the browser chrome colour (theme.svelte.ts, app.html theme-color).',
		'export const PAGE_BG = {',
		`\tlight: '${page.light.toLowerCase()}',`,
		`\tdark: '${page.dark.toLowerCase()}'`,
		'} as const;',
		''
	].join('\n');
}

/** @param {string} html @param {Map<string, ColorToken>} byPath */
function renderHtml(html, byPath) {
	const page = byPath.get('color.surface.page');
	if (!page) throw new Error('missing token color.surface.page');
	let out = html;
	for (const scope of /** @type {const} */ (['light', 'dark'])) {
		const meta = new RegExp(
			`(<meta name="theme-color" content=")[^"]*(" media="\\(prefers-color-scheme: ${scope}\\)" />)`
		);
		if (!meta.test(out)) throw new Error(`${HTML}: no ${scope} theme-color meta`);
		out = out.replace(meta, `$1${page[scope].toLowerCase()}$2`);
	}
	return out;
}

const args = process.argv.slice(2);
const check = args.includes('--check');
const tokensAt = args.indexOf('--tokens');
const tokensPath = tokensAt >= 0 ? args[tokensAt + 1] : join(ROOT, 'design/tokens.json');

const colors = colorTokens(JSON.parse(readFileSync(tokensPath, 'utf8')));
const byPath = new Map(colors.map((t) => [t.path, t]));
const outputs = [
	[CSS_OUT, renderCss(colors)],
	[TS_OUT, renderTs(byPath)],
	[PAGE_OUT, renderPageTs(byPath)],
	[HTML, renderHtml(readFileSync(join(ROOT, HTML), 'utf8'), byPath)]
];

let stale = 0;
for (const [path, content] of outputs) {
	const file = join(ROOT, path);
	let current = '';
	try {
		current = readFileSync(file, 'utf8');
	} catch {
		/* not generated yet */
	}
	if (current === content) continue;
	if (check) {
		console.error(`stale: ${path}. Run bun run tokens.`);
		stale++;
	} else {
		writeFileSync(file, content);
		console.log(`wrote ${path}`);
	}
}
if (check && stale === 0) console.log('tokens: generated files are up to date');
process.exit(stale ? 1 : 0);
