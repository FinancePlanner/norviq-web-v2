"""Write design/vig-motion.fixtures.json: inputs and expected outputs for the Vig motion drivers (BRD-001).

    python3 -I scripts/brand/vig_motion_fixtures.py            # write
    python3 -I scripts/brand/vig_motion_fixtures.py --check    # exit 1 if the committed file is stale

This is the reference arithmetic. src/lib/vig-motion.ts and the iOS Design/VigMotion.swift must
agree with it; their tests load the fixtures this writes. Standard library only.
"""

import argparse
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MOTION = ROOT / "design" / "vig-motion.json"
FIXTURES = ROOT / "design" / "vig-motion.fixtures.json"
DIGITS = 9


def clamp(v, lo, hi):
    return max(lo, min(hi, v))


def ease(kind, u):
    u = clamp(u, 0.0, 1.0)
    if kind == "linear":
        return u
    if kind == "sine":
        return 0.5 - 0.5 * math.cos(math.pi * u)
    if kind == "decelerate":
        return 1 - (1 - u) ** 3
    raise ValueError(kind)


def entrance(m, t):
    e = m["entrance"]
    k = ease(e["easing"], t / e["durationSeconds"])
    return {
        "opacity": e["fromOpacity"] + (1 - e["fromOpacity"]) * k,
        "rise": e["fromRise"] * (1 - k),
        "yawDegrees": e["fromYawDegrees"] * (1 - k),
    }


def sway(m, t):
    i = m["idle"]
    s = max(0.0, t - m["entrance"]["durationSeconds"]) if i["startsAfterEntrance"] else t
    return i["amplitudeDegrees"] * math.sin(2 * math.pi * s / i["periodSeconds"])


def pointer_target(m, x, y):
    p = m["pointer"]
    return {"yawDegrees": clamp(x, -1, 1) * p["maxYawDegrees"], "pitchDegrees": -clamp(y, -1, 1) * p["maxPitchDegrees"]}


def pointer_time_constant(m, active):
    return m["pointer"]["followSeconds"] if active else m["pointer"]["returnSeconds"]


def approach(current, target, dt, tau):
    if tau <= 0:
        return target
    return current + (target - current) * (1 - math.exp(-dt / tau))


def pose(m, t, pointer_yaw, pointer_pitch):
    lim = m["limits"]
    e = entrance(m, t)
    return {
        "opacity": e["opacity"],
        "rise": e["rise"],
        "yawDegrees": clamp(e["yawDegrees"] + sway(m, t) + pointer_yaw, -lim["maxYawDegrees"], lim["maxYawDegrees"]),
        "pitchDegrees": clamp(pointer_pitch, -lim["maxPitchDegrees"], lim["maxPitchDegrees"]),
    }


def r(v):
    if isinstance(v, dict):
        return {k: r(x) for k, x in v.items()}
    v = round(v, DIGITS)
    return 0.0 if v == 0 else v  # no -0.0 in the file


def build(m):
    d = m["entrance"]["durationSeconds"]
    period = m["idle"]["periodSeconds"]
    return {
        "about": "Generated by scripts/brand/vig_motion_fixtures.py from vig-motion.json. Do not edit. Both clients' tests load this file.",
        "motionVersion": m["version"],
        "tolerance": 1e-6,
        "ease": [{"easing": k, "u": u, "expect": r(ease(k, u))} for k in ("linear", "sine", "decelerate") for u in (-0.5, 0, 0.25, 0.5, 0.75, 1, 1.5)],
        "entrance": [{"t": t, "expect": r(entrance(m, t))} for t in (0, d * 0.25, d * 0.5, d, d + 1)],
        "sway": [{"t": t, "expect": r(sway(m, t))} for t in (0, d, d + period / 4, d + period / 2, d + period * 3 / 4, d + period, d + period * 2.25)],
        "pointerTarget": [{"x": x, "y": y, "expect": r(pointer_target(m, x, y))} for x, y in ((0, 0), (1, 1), (-1, -1), (0.5, -0.25), (3, -7))],
        "pointerTimeConstant": [{"active": a, "expect": r(pointer_time_constant(m, a))} for a in (True, False)],
        "approach": [{"current": c, "target": tg, "dt": dt, "tau": tau, "expect": r(approach(c, tg, dt, tau))}
                     for c, tg, dt, tau in ((0, 10, 1 / 60, 0.35), (10, 0, 1 / 60, 0.8), (0, 10, 0.35, 0.35), (5, 5, 0.1, 0.35), (0, 10, 0.1, 0))],  # fmt: skip
        "pose": [{"t": t, "pointerYaw": py, "pointerPitch": pp, "expect": r(pose(m, t, py, pp))}
                 for t, py, pp in ((0, 0, 0), (d / 2, 0, 0), (d + period / 4, 0, 0), (d + period / 4, 10, -6), (d + period * 3 / 4, -10, 9), (0, 10, 0))],  # fmt: skip
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = json.dumps(build(json.loads(MOTION.read_text())), indent=2) + "\n"
    if args.check:
        if not FIXTURES.exists() or FIXTURES.read_text() != text:
            print("vig-motion.fixtures.json is stale: run python3 -I scripts/brand/vig_motion_fixtures.py", file=sys.stderr)
            sys.exit(1)
        print("vig-motion fixtures: up to date")
        return
    FIXTURES.write_text(text)
    print(f"wrote {FIXTURES.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
