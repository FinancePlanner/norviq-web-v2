type Golden = { id: string; className: string; width: string; height: string; theme: string | null; option: Record<string, unknown> };
const g = golden as unknown as Record<string, Golden & { svg?: string }>;

/** JSON round trip with functions as "__fn__", the way the golden extractor wrote them. */
function plain(value: unknown): unknown {
	return JSON.parse(JSON.stringify(value, (_k, v) => (typeof v === 'function' ? '__fn__' : v)));
}

/** The Go option minus what the port deliberately leaves out (see options.ts). */
function expected(name: string): Record<string, unknown> {
	const opt = structuredClone(g[name].option);
	if (JSON.stringify(opt.title) === '{}') delete opt.title;
	if (JSON.stringify(opt.toolbox) === '{}') delete opt.toolbox;
	if (Array.isArray(opt.series)) for (const s of opt.series as Record<string, unknown>[]) delete s.markLine;
	return opt;
}

function matchesGolden(name: string, spec: ChartSpec | null) {
	expect(spec, name).not.toBeNull();
	const want = g[name];
	expect(spec!.id).toBe(want.id);
	expect(spec!.width).toBe(want.width);
	expect(spec!.height).toBe(want.height);
	expect(spec!.class ?? '').toBe(want.className);
	expect(plain(spec!.option)).toEqual(expected(name));
}

