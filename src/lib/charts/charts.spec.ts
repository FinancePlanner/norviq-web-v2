// Ported from charts_test.go, crypto_charts_test.go, multiseries_test.go,
// pulse_test.go, palette_test.go, donut_svg_test.go, growth_sparkline_test.go.
describe('Go chart tests', () => {
	it('wealth line uses a normalized id and interactive options', () => {
		const s = wealthLine('wealth-chart', ['Jan 2', 'Jan 9'], [100000, 105000])!;
		expect(s.id).toBe('wealth_chart');
		const o = s.option as Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any
		expect(o.tooltip).toMatchObject({ trigger: 'axis', triggerOn: 'mousemove|click', axisPointer: { snap: true } });
		expect(o.series[0].emphasis.focus).toBe('series');
	});

	it('allocation pie is interactive', () => {
		const o = allocationPie('allocation-chart', ['Tech', 'Health'], [40, 30])!.option as Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any
		expect(o.tooltip).toMatchObject({ trigger: 'item', triggerOn: 'mousemove|click', formatter: '{b}: {d}%' });
		expect(o.series[0].emphasis.focus).toBe('self');
	});

	it('sparkline disables the tooltip', () => {
		expect((sparkline('spark-aapl', [1, 2, 3, 2.5])!.option as Record<string, unknown>).tooltip).toEqual({ show: false });
	});

	it('empty input renders nothing', () => {
		expect(wealthLine('', [], [])).toBeNull();
		expect(allocationPie('', [], [])).toBeNull();
		expect(sparkline('', [1])).toBeNull();
		expect(sentimentHistoryLine('', ['a'], [1])).toBeNull();
		expect(multiSeriesLine('', [], [])).toBeNull();
		expect(cryptoBubbles('x', [], { scaleMaxPct: 5 })).toBeNull();
		expect(marketHeatmap('x', [])).toBeNull();
	});

	it('heatColorScaled change mode', () => {
		expect(heatColorScaled(15, 15, 'change')).toBe('#089981');
		expect(heatColorScaled(40, 15, 'change')).toBe('#089981');
		expect(heatColorScaled(-15, 15, 'change')).toBe('#f23645');
		expect(heatColorScaled(0, 15, 'change')).toBe('#414454');
	});

	it('heatColorScaled ATH distance', () => {
		expect(heatColorScaled(0, 90, 'athDistance')).toBe('#089981');
		expect(heatColorScaled(-90, 90, 'athDistance')).toBe('#f23645');
		expect(heatColorScaled(-45, 90, 'athDistance')).toBe('#414454');
	});

	it('treemap tooltips name the period and have a millions tier', () => {
		const tip = treemapTooltip('1W');
		expect(tip({ data: { symbol: 'BTC', fullName: 'Bitcoin', value: 3e8, changePct: 4 } })).toBe('<b>BTC</b> · Bitcoin<br/>+4.00% 1W · $300M cap');
		expect(treemapTooltip('today')({ name: 'Tech', data: { changePct: 0 } })).toBe('Tech');
		expect(treemapLabel({ data: { symbol: 'AAPL', changePct: -1.26 } })).toBe('AAPL\n-1.3%');
		expect(capFormatter(3e12)).toBe('3.00T');
		expect(capFormatter(2.5e9)).toBe('2.5B');
		expect(capFormatter(25e9)).toBe('25B');
	});

	it('bubbles build a force graph', () => {
		const s = cryptoBubbles(
			'crypto_bubbles_1w',
			[
				{ symbol: 'BTC', name: 'Bitcoin', marketCap: 1e12, changePct: 3 },
				{ symbol: 'ETH', name: 'Ethereum', marketCap: 3e11, changePct: -2 },
				{ symbol: 'DOGE', name: 'Dogecoin', marketCap: 2e10, changePct: 9 }
			],
			{ scaleMaxPct: 15, periodLabel: '1W' }
		)!;
		const series = (s.option as Record<string, any>).series[0]; // eslint-disable-line @typescript-eslint/no-explicit-any
		expect(series).toMatchObject({ type: 'graph', layout: 'force' });
		expect(series.data[0].name).toBe('BTC');
		expect(bubbleTooltip('1W')({ data: { name: 'BTC', fullName: 'Bitcoin', changePct: 3, marketCap: 1e12, symbolSize: 110 } })).toContain('1W');
		expect(bubbleLabel({ data: { name: 'X', changePct: 1, symbolSize: 20 } })).toBe('X');
		expect(bubbleLabel({ data: { name: 'X', changePct: 1, symbolSize: 40 } })).toBe('X\n+1.0%');
	});

	it('bubble sizes grow with market cap and stay clamped', () => {
		const sizes = bubbleSizes([1e12, 3e11, 2e10, 1e8]);
		for (let i = 1; i < sizes.length; i++) expect(sizes[i]).toBeLessThanOrEqual(sizes[i - 1]);
		expect(sizes[0]).toBe(bubbleMaxSize);
		expect(sizes[sizes.length - 1]).toBeGreaterThanOrEqual(bubbleMinSize);
	});

	it('multi-series formatters are callable and Go-shaped', () => {
		expect(compactAxisFormatter(1.25e9)).toBe('1.3B');
		expect(compactAxisFormatter(-2500)).toBe('-2.5K');
		expect(percentAxisFormatter(0.425)).toBe('42.5%');
		expect(percentAxisFormatter('-')).toBe('-');
		expect(ratioAxisFormatter(null)).toBe('-');
		expect(decimalAxisFormatter(undefined)).toBe('-');
		const o = multiSeriesLine('margin-chart', ['FY2026'], [{ name: 'Gross margin', format: 'percent', values: [0.425] }])!.option as Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any
		expect(o.tooltip.valueFormatter).toBe(percentAxisFormatter);
		expect(o.yAxis[0].axisLabel.formatter).toBe(percentAxisFormatter);
		expect(o.series[0].data).toEqual([{ value: 0.425 }]);
	});

	it('spend pillar bar is one stacked row and drops empty slices', () => {
		const s = spendPillarBar('cc-pillars', [
			{ name: 'Fixed', value: 100 },
			{ name: 'Empty', value: 0 },
			{ name: 'Refund', value: -50 }
		])!;
		expect(s.id).toBe('cc-pillars');
		const o = s.option as Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any
		expect(o.series.map((x: { name: string }) => x.name)).toEqual(['Fixed']);
		expect(o.xAxis.type).toBe('value');
		expect(spendPillarBar('cc-pillars', [])).toBeNull();
		expect(pillarTooltip({ marker: '•', seriesName: 'Fixed', value: 2400 })).toMatch(/^• Fixed: \$2.?400$/);
	});

	it('activity heatmap uses calendar coordinates and a sequential ramp', () => {
		const s = activityHeatmap('cc-heatmap', '2026-01-01', '2026-03-01', { '2026-02-01': 2 })!;
		const o = s.option as Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any
		expect(o.calendar.range).toEqual(['2026-01-01', '2026-03-01']);
		expect(o.series).toMatchObject({ type: 'heatmap', coordinateSystem: 'calendar' });
		expect(o.visualMap.type).toBe('continuous');
		expect(o.visualMap.inRange.color).toHaveLength(4);
		expect(heatmapTooltip({ value: ['2026-02-01', 1] })).toBe('2026-02-01<br/>1 event');
		expect(activityHeatmap('cc-heatmap', '2026-01-01', '2026-03-01', null)).toBeNull();
		expect(activityHeatmap('cc-heatmap', new Date('2026-08-12'), new Date('2026-01-01'), { '2026-05-01': 1 })).toBeNull();
	});

	it('the allocation palette is the single categorical source', () => {
		expect(multiSeriesColors).toEqual(allocationColors);
		expect(new Set(allocationColors).size).toBe(allocationColors.length);
		for (const retired of ['#F97316', '#B0803A', '#EAB308', '#78716C', '#EC4899']) expect(allocationColors).not.toContain(retired);
		expect(allocationColor(0)).toBe(allocationColors[0]);
		expect(allocationColor(allocationColors.length)).toBe(allocationColors[0]);
		expect(allocationColor(-3)).toBe(allocationColors[0]);
	});

	it('donut arcs sum to a full ring and normalise', () => {
		const dash = (svg: string) => [...svg.matchAll(/stroke-dasharray="([0-9.]+) ([0-9.]+)"/g)].map((m) => Number(m[1]));
		const svg = donutSVG([{ label: 'AAPL', weight: 60 }, { label: 'MSFT', weight: 30 }, { label: 'Other', weight: 10 }]);
		expect(dash(svg).reduce((a, b) => a + b, 0)).toBeCloseTo(100, 2);
		expect(svg).toContain('role="img"');
		expect(svg).toContain('AAPL 60.0%');
		expect(dash(donutSVG([{ label: 'A', weight: 30 }, { label: 'B', weight: 10 }]))).toEqual([75, 25]);
		expect(dash(donutSVG([{ label: 'CASH', weight: 100 }]))).toEqual([100]);
		expect(donutSVG(null)).toBe('');
		expect(donutSVG([{ label: 'A', weight: 0 }])).toBe('');
		expect(donutSVG([{ label: '<script>x</script>', weight: 100 }])).not.toContain('<script>');
	});

	it('growth sparkline needs two points and draws a zero line when crossing zero', () => {
		expect(growthSparklineSVG([{ label: 'a', value: 1 }], 'positive')).toBe('');
		const svg = growthSparklineSVG(
			[
				{ label: '2020', value: 5 },
				{ label: '2022', value: -3 }
			],
			'positive'
		);
		expect(svg).toContain('<polyline');
		expect(svg).toContain('fin-growth-sparkline-zero');
	});
});
